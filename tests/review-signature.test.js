/* Verificación aislada de huella de contenido; no necesita un navegador. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const text=fs.readFileSync(require('node:path').join(__dirname,'../pedigree.js'),'utf8');
const begin=text.indexOf('function pedigreeContentSignature() {');
const end=text.indexOf('function familyReviewStatus() {');
assert(begin>0 && end>begin);
const helpers=text.slice(begin,end);
const initial={schema_version:'4.12',family_id:'FAM1',indication:'Prueba',people:[{uid:'P1',record_type:'person',age:42}],review_status:{reviewed:false,reviewed_at:''}};
const ctx={family:JSON.parse(JSON.stringify(initial))};
vm.createContext(ctx);
vm.runInContext(helpers+'\nthis.signature=pedigreeContentSignature;this.reviewState=reviewContentState;',ctx);
const sig=ctx.signature();
ctx.family.review_status={reviewed:true,reviewed_at:'2026-10-15T09:00:00Z',reviewed_signature:sig};
assert.equal(ctx.reviewState(),'current');
ctx.family.review_status.reviewed_at='2026-10-15T10:00:00Z';
assert.equal(ctx.reviewState(),'current','Cambiar solo los metadatos de revisión no ensucia la huella');
ctx.family.people[0].age=43;
assert.equal(ctx.reviewState(),'outdated');
ctx.family.people[0].age=42;
assert.equal(ctx.reviewState(),'current','Deshacer recupera la firma');
ctx.family.review_status.reviewed_signature='';
assert.equal(ctx.reviewState(),'historical','Casos antiguos sin huella');
ctx.family.review_status.reviewed=false;
assert.equal(ctx.reviewState(),'pending');
console.log('Firma de revisión: actual, desactualizada, histórica, deshacer y exclusión de metadatos superados.');
